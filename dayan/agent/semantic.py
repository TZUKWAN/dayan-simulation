# 编译正则
_COMPILED = [(re.compile(pat), ids) for pat, ids in SEMANTIC_MAP.items()]


def match_requirement(text: str) -> list[str]:
    """语义匹配：返回推荐的模型 ID 列表（去重、按匹配优先级排序）。"""
    seen = []
    for pat, ids in _COMPILED:
        if pat.search(text):
            for mid in ids:
                if mid not in seen:
                    seen.append(mid)
    return seen


def best_model_for(text: str) -> str | None:
    """返回最匹配的模型 ID（首选），无匹配返回 None。"""
    ids = match_requirement(text)
    return ids[0] if ids else None
